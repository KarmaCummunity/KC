#!/usr/bin/env node
// Keeps the Deno copy of the external post import domain code in step with `@kc/domain` (ADR-008).
//
// Edge Functions run on Deno, which needs explicit `.ts` import paths and cannot reach into the
// app packages once deployed, so the pure stages (normalize, scrub, validate, time, confidence)
// are copied into `supabase/functions/_shared/post-extraction/domain/`. The copy is generated,
// never edited by hand: `node scripts/sync-post-extraction-mirror.mjs` rewrites it, and the
// test next to this file fails when it is out of date.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DOMAIN = 'app/packages/domain/src';
export const MIRROR_DIR = 'supabase/functions/_shared/post-extraction/domain';

/** Mirrored source file -> its path under the domain package. */
const SOURCES = {
  'language.ts': 'language.ts',
  'ImportExtractionError.ts': 'imports/ImportExtractionError.ts',
  'importTypes.ts': 'imports/importTypes.ts',
  'israelTime.ts': 'imports/israelTime.ts',
  'normalizeMessage.ts': 'imports/normalizeMessage.ts',
  'scrubPii.ts': 'imports/scrubPii.ts',
  'prepareImportText.ts': 'imports/prepareImportText.ts',
  'fingerprint.ts': 'imports/fingerprint.ts',
  'validateExtraction.ts': 'imports/validateExtraction.ts',
  'resolveRelativeTime.ts': 'imports/resolveRelativeTime.ts',
  'recalibrateConfidence.ts': 'imports/recalibrateConfidence.ts',
};

/** Domain import specifiers that are not siblings in the mirror, and the mirrored file standing in. */
const REMAPPED = { '../errors': './errors.ts', '../language': './language.ts', '../rides/rideSchedule': './rideLimits.ts' };

const header = (from) =>
  `// GENERATED by scripts/sync-post-extraction-mirror.mjs from ${from}. Do not edit: change the domain file and run the script.\n`;

/** `./name` -> `./name.ts`; the remapped parents point at their mirror stand-ins. */
function rewriteImports(text) {
  return text.replace(/from\s+'([^']+)'/g, (whole, spec) => {
    const target = REMAPPED[spec] ?? (spec.startsWith('./') ? `${spec}.ts` : null);
    if (!target) throw new Error(`mirror: unexpected import '${spec}'`);
    return `from '${target}'`;
  });
}

/** The ride seat limits the validator needs, read from the domain so they cannot drift. */
function rideLimits() {
  const source = readFileSync(join(ROOT, DOMAIN, 'rides/rideSchedule.ts'), 'utf8');
  const read = (name) => {
    const m = source.match(new RegExp(`export const ${name} = (\\d+);`));
    if (!m) throw new Error(`mirror: ${name} not found in rideSchedule.ts`);
    return m[1];
  };
  return `${header(`${DOMAIN}/rides/rideSchedule.ts`)}export const RIDE_MIN_SEATS = ${read('RIDE_MIN_SEATS')};\nexport const RIDE_MAX_SEATS = ${read('RIDE_MAX_SEATS')};\n`;
}

/** The text before this marker in errors.ts is DomainError and ValidationError, the only classes the stages use. */
const ERRORS_CUT = '/** What a missing backend object is';

/** Just the two base error classes: the rest of errors.ts is app-side and fails Deno's stricter `override` rule. */
function baseErrors() {
  const source = readFileSync(join(ROOT, DOMAIN, 'errors.ts'), 'utf8');
  const end = source.indexOf(ERRORS_CUT);
  if (end < 0) throw new Error('mirror: errors.ts no longer has the cut marker; update ERRORS_CUT');
  return header(`${DOMAIN}/errors.ts (DomainError, ValidationError)`) + source.slice(0, end).trimEnd() + '\n';
}

/** File name -> generated text, for every file of the mirror. */
export function generateMirror() {
  const files = new Map();
  for (const [name, path] of Object.entries(SOURCES)) {
    const text = readFileSync(join(ROOT, DOMAIN, path), 'utf8');
    files.set(name, header(`${DOMAIN}/${path}`) + rewriteImports(text));
  }
  files.set('errors.ts', baseErrors());
  files.set('rideLimits.ts', rideLimits());
  return files;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  mkdirSync(join(ROOT, MIRROR_DIR), { recursive: true });
  for (const [name, text] of generateMirror()) writeFileSync(join(ROOT, MIRROR_DIR, name), text);
  console.log(`mirror written: ${MIRROR_DIR}`);
}

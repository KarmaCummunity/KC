// Markdown rendering of the application migration map (see scripts/app-migration-map.mjs).

const STATUS_LABEL = { same: '1:1', renamed: '1:1 (renamed)', changed: 'CHANGED', removed: 'REMOVED', missing: 'MISSING' };
const KIND_LABEL = { rpc: 'RPCs', table: 'Tables and views', bucket: 'Storage buckets', channel: 'Realtime channels', postgres_changes: 'postgres_changes subscriptions', edge_function: 'Edge Function invokes' };
const AREA_TITLE = (area) =>
  area === 'mobile' ? '`apps/mobile` (direct calls outside the adapters)' : area.startsWith('fn:') ? `Edge Function \`${area.slice(3)}\`` : `\`infrastructure-supabase/src/${area === '(root)' ? '' : `${area}/`}\``;

const cell = (text) => String(text).replaceAll('|', '\\|').replaceAll('\n', ' ');
const code = (text) => `\`${String(text).replaceAll('`', "'")}\``;

function targetText(target) {
  if (target.type === 'rpc') return target.signature.map(code).join('<br>');
  if (target.type === 'table') return `table ${code(target.name)}`;
  return `${target.type} ${code(target.name)}`;
}

function errorText(row) {
  const errors = new Map();
  for (const target of row.targets) for (const error of target.errors ?? []) errors.set(error.code, error.knownToApp);
  return [...errors].map(([name, known]) => `${code(name)}${known ? '' : ' †'}`).join(', ');
}

function table(header, lines) {
  return [`| ${header.join(' | ')} |`, `| ${header.map(() => '---').join(' | ')} |`, ...lines.map((line) => `| ${line.map(cell).join(' | ')} |`)].join('\n');
}

/** @param {object} map output of buildMap @returns {string} the document */
export function renderMarkdown(map) {
  const out = [];
  const push = (...parts) => out.push(...parts, '');
  const sum = (key) => Object.values(map.totals).reduce((n, t) => n + t[key], 0);

  push('# Application migration map — old schema → production baseline');
  push(
    '> Generated by `node scripts/app-migration-map.mjs` from `scripts/app-migration-map.rows.mjs` (authored rows), `docs/db/app-usage-inventory.json` (call sites, `scripts/db-usage-inventory.mjs`), the old and the baseline generated types, and the baseline sources. **Do not edit by hand**; the machine-readable twin is `app-migration-map.json`. Design: [`target-design.md`](./target-design.md) §8–§9.',
  );
  push(
    'The application (`app/packages/infrastructure-supabase`, `app/apps/mobile`) and the Edge Functions (`supabase/functions`) still address the old schema. This map says, for every object they address, what replaces it in the baseline (`supabase/schemas` → `supabase/baseline/0001_baseline.sql`), so the adapters can move in parallel without guessing.',
  );

  push('## 1. Headline numbers');
  push(table(
    ['Kind', 'Objects used', '1:1', '1:1 (renamed)', 'CHANGED', 'REMOVED', 'MISSING'],
    [
      ...Object.entries(map.totals).map(([kind, t]) => [KIND_LABEL[kind], t.objects, t.same, t.renamed, t.changed, t.removed, t.missing]),
      ['**Total**', sum('objects'), sum('same'), sum('renamed'), sum('changed'), sum('removed'), sum('missing')],
    ],
  ));
  push('### Launch scope');
  push('Every row carries `launch` (spec D102, `docs/spec/96_launch_and_first_group_plan.md`, `docs/spec/14_roadmap.md`): **core** platform needed by every launch user · **wedge** needed only by the launch worlds (items, rides, food, time) · **later** portal worlds and tools behind a flag (housing, knowledge, challenges, money and org finance, WhatsApp bot, back-office tools, survey admin, analytics).');
  const tiers = ['core', 'wedge', 'later'].filter((tier) => map.launchTotals[tier]);
  const launchSum = (key) => ['core', 'wedge'].reduce((n, tier) => n + (map.launchTotals[tier]?.[key] ?? 0), 0);
  push(table(
    ['Launch tier', 'Objects used', '1:1', '1:1 (renamed)', 'CHANGED', 'REMOVED', 'MISSING'],
    [
      ...tiers.map((tier) => [tier, ...['objects', 'same', 'renamed', 'changed', 'removed', 'missing'].map((k) => map.launchTotals[tier][k])]),
      ['**Launch-critical (core + wedge)**', ...['objects', 'same', 'renamed', 'changed', 'removed', 'missing'].map(launchSum)],
    ],
  ));
  push('Status: **1:1** same name and call shape · **1:1 (renamed)** mechanical rename of the function or its arguments · **CHANGED** the caller\'s logic changes · **REMOVED** no replacement by design · **MISSING** the baseline has no equivalent although the code needs one (§4). Confidence: **high** read in the baseline source, **medium** inferred from names and generated types.');

  push('## 2. Rules that hold everywhere');
  push(map.notes.map((note) => `- ${note}`).join('\n'));

  // Adapters first, then the mobile app, then the Edge Functions.
  const rank = (area) => (area.startsWith('fn:') ? 2 : area === 'mobile' ? 1 : 0);
  const areas = Object.keys(map.modules).sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
  push('## 3. Map by application module');
  push(table(
    ['Module', 'Call sites', '1:1', 'Logic changes', 'Removed', 'MISSING'],
    areas.map((area) => [AREA_TITLE(area), ...['callSites', 'oneToOne', 'changed', 'removed', 'missing'].map((k) => map.modules[area][k])]),
  ));
  const firstShown = new Map();
  for (const area of areas) {
    const m = map.modules[area];
    push(`### ${AREA_TITLE(area)}`);
    push(`${m.callSites} call sites: ${m.oneToOne} map 1:1, ${m.changed} need logic changes, ${m.removed} removed, ${m.missing} MISSING.`);
    const lines = [];
    for (const row of map.rows.filter((r) => r.areas.includes(area))) {
      const sites = row.callSites.filter((s) => s.area === area);
      const where = [...new Set(sites.map((s) => `${s.file.split('/').pop()}:${s.line}`))].join(', ');
      const name = `${code(row.old)}${row.kind === 'rpc' ? '' : ` (${row.kind.replace('_', ' ')})`}`;
      const status = `${STATUS_LABEL[row.status]}${row.missing ? ` ${row.missing}` : ''}`;
      const launch = row.launch;
      const key = `${row.kind}:${row.old}`;
      if (firstShown.has(key)) {
        lines.push([name, launch, status, `see ${AREA_TITLE(firstShown.get(key))}`, '', '', '', where]);
        continue;
      }
      firstShown.set(key, area);
      lines.push([name, launch, status, row.targets.map(targetText).join('<br>') || '—', row.note, errorText(row), row.confidence, where]);
    }
    push(table(['Old object', 'Launch', 'Status', 'Baseline replacement', 'What changes for the caller', 'Errors raised (new)', 'Conf.', 'Call sites'], lines));
  }

  push('## 4. MISSING — what the baseline does not provide');
  push('Every capability the application or an Edge Function uses today that has no equivalent in the baseline, **launch blockers first** (tier core or wedge, and something must be built). **Action**: `build` add to the baseline (module named) · `rls-read` already possible with direct reads, no new object · `drop` remove from the app · `defer` hide behind a feature flag.');
  push(table(
    ['Id', 'Blocker', 'Tier', 'Capability', 'Old objects', 'Used by', 'Spec', 'Needed at launch', 'Action', 'Recommendation'],
    map.missing.map((m) => {
      const objects = map.rows.filter((r) => r.missing === m.id).map((r) => r.old);
      const shown = objects.length > 8 ? `${objects.slice(0, 8).map(code).join(', ')} … (${objects.length})` : objects.map(code).join(', ');
      return [m.id, m.blocker ? '**yes**' : 'no', m.tier, m.title, shown, m.usedBy, m.spec, m.launch, m.action, m.recommendation];
    }),
  ));

  push('## 5. Work packages for the adapter phase');
  push('In launch order: after package *n* the app is shippable with everything up to *n* on the new database; `P6` is the launch line, and each `L` package ships on its own behind its flag. Two agents never edit the same file: a package owns the folders listed (paths are under `app/packages/infrastructure-supabase/src/` unless they say otherwise), and exceptions are named on both sides.');
  push(table(
    ['Package', 'Launch', 'Objects', '1:1', 'Changed', 'Removed', 'MISSING', 'May run in parallel with'],
    map.packages.map((p) => [`${p.id} — ${p.title}`, p.launch, p.counts.objects, p.counts.oneToOne, p.counts.changed, p.counts.removed, p.counts.missing, p.parallelWith.join(', ') || '—']),
  ));
  for (const p of map.packages) {
    push(`### ${p.id} — ${p.title}`);
    push([
      `- **Owns:** ${p.files.map(code).join(', ')}`,
      `- **Work:** ${p.work}`,
      `- **Must pass:** ${p.tests.join('; ')}`,
      `- **If reached before it is migrated:** ${p.degrade}`,
      `- **Risks:** ${p.risks}`,
    ].join('\n'));
  }

  push('## 6. Edge Functions');
  push('`keep` no database change · `retarget` same job, renamed objects · `rewrite` · `obsolete` delete · `park` not deployed at launch · `done` already on the baseline.');
  push(table(['Function', 'Verdict', 'Uses today', 'What changes'], map.edgeFunctions.map((f) => [code(f.name), f.verdict, f.uses, f.change])));

  return `${out.join('\n').trimEnd()}\n`;
}

#!/usr/bin/env node
// Assembles the production baseline migration from its per-module source files.
//
// Source:  supabase/schemas/<NN>_<module>/<NNN>_<topic>.sql   (authored, reviewed)
// Output:  supabase/migrations/0001_baseline.sql               (generated, committed, frozen)
//
// The output is a plain concatenation in path order, so the baseline is byte-for-byte
// reproducible from the source and a reviewer only ever reads the small source files.
//
// Usage:
//   node scripts/assemble-baseline.mjs           write the baseline
//   node scripts/assemble-baseline.mjs --check   exit 1 when the committed baseline is stale
//
// Design: docs/db/target-design.md §10.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE_DIR = join(ROOT, 'supabase', 'schemas');
export const OUTPUT_FILE = join(ROOT, 'supabase', 'migrations', '0001_baseline.sql');

/** Same cap as every other file in the repo (`pnpm lint:arch`). */
export const MAX_SOURCE_LINES = 300;

const MODULE_NAME = /^\d{2}_[a-z0-9_]+$/;
const FILE_NAME = /^\d{3}_[a-z0-9_]+\.sql$/;

const HEADER = [
  '-- Karma Community — production baseline.',
  '-- GENERATED by scripts/assemble-baseline.mjs from supabase/schemas/. Do not edit by hand:',
  '-- change the source file named above each section and regenerate.',
  '',
].join('\n');

/**
 * List the source files of a schema directory in assembly order.
 * Returns `{ files, errors }`; `files` holds `{ module, name, path }` sorted by module, then name.
 */
export function listSources(sourceDir) {
  const files = [];
  const errors = [];
  const entries = readdirSync(sourceDir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    if (!entry.isDirectory()) continue; // README.md and other loose files are not schema source
    if (!MODULE_NAME.test(entry.name)) {
      errors.push(`module folder "${entry.name}" must be named NN_snake_case`);
      continue;
    }
    const names = readdirSync(join(sourceDir, entry.name)).sort();
    for (const name of names) {
      if (!FILE_NAME.test(name)) {
        errors.push(`${entry.name}/${name} must be named NNN_snake_case.sql`);
        continue;
      }
      files.push({ module: entry.name, name, path: join(sourceDir, entry.name, name) });
    }
  }
  return { files, errors };
}

/** Validate one source file's text; returns a list of problems (empty = valid). */
export function validateSource(label, text) {
  const errors = [];
  if (text.includes('\r')) errors.push(`${label}: carriage returns are not allowed (use LF line endings)`);
  if (text.trim() === '') errors.push(`${label}: file is empty`);
  const lineCount = text.replace(/\n$/, '').split('\n').length;
  if (lineCount > MAX_SOURCE_LINES) {
    errors.push(`${label}: ${lineCount} lines exceeds the ${MAX_SOURCE_LINES}-line cap; split the file`);
  }
  return errors;
}

/**
 * Build the baseline text for a schema directory.
 * Returns `{ sql, errors }`; `sql` is only meaningful when `errors` is empty.
 */
export function assembleBaseline(sourceDir) {
  const { files, errors } = listSources(sourceDir);
  const sections = [];
  for (const file of files) {
    const label = `${file.module}/${file.name}`;
    const text = readFileSync(file.path, 'utf8');
    errors.push(...validateSource(label, text));
    sections.push(`-- >>> supabase/schemas/${label}\n${text.trim()}\n`);
  }
  if (files.length === 0 && errors.length === 0) errors.push('no schema source files found');
  return { sql: `${HEADER}\n${sections.join('\n')}`, errors };
}

/** CLI entry: write the baseline, or with `--check` compare it to the committed file. */
function main(argv) {
  const check = argv.includes('--check');
  const { sql, errors } = assembleBaseline(SOURCE_DIR);
  if (errors.length > 0) {
    for (const error of errors) console.error(`assemble-baseline: ${error}`);
    return 1;
  }
  if (!check) {
    writeFileSync(OUTPUT_FILE, sql);
    console.log(`assemble-baseline: wrote ${OUTPUT_FILE}`);
    return 0;
  }
  const committed = existsSync(OUTPUT_FILE) ? readFileSync(OUTPUT_FILE, 'utf8') : '';
  if (committed !== sql) {
    console.error('assemble-baseline: supabase/migrations/0001_baseline.sql is stale (it must equal the assembly of supabase/schemas; later changes go in new migrations, never in 0001).');
    console.error('Only while the baseline is still unreleased: node scripts/assemble-baseline.mjs');
    return 1;
  }
  console.log('assemble-baseline: baseline is up to date');
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exit(main(process.argv.slice(2)));
}

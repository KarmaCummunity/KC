// Tests for the Deno mirror of the external post import domain code (ADR-008).
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { MIRROR_DIR, generateMirror } from './sync-post-extraction-mirror.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

test('every import of a mirrored file is an explicit .ts path of another mirrored file', () => {
  const files = generateMirror();
  assert.ok(files.size >= 10, 'the pure import stages are mirrored');
  for (const [name, text] of files) {
    for (const m of text.matchAll(/from\s+'([^']+)'/g)) {
      assert.match(m[1], /^\.\/[A-Za-z0-9]+\.ts$/, `${name} imports ${m[1]}`);
      assert.ok(files.has(m[1].slice(2)), `${name} imports ${m[1]}, which is not mirrored`);
    }
  }
});

test('every mirrored file says it is generated and where it comes from', () => {
  for (const [name, text] of generateMirror()) {
    assert.match(text.split('\n')[0], /^\/\/ GENERATED by scripts\/sync-post-extraction-mirror\.mjs/, name);
  }
});

test('the ride seat limits are read from the domain, not copied by hand', () => {
  const limits = generateMirror().get('rideLimits.ts');
  const source = readFileSync(join(ROOT, 'app/packages/domain/src/rides/rideSchedule.ts'), 'utf8');
  const min = source.match(/RIDE_MIN_SEATS = (\d+)/)[1];
  const max = source.match(/RIDE_MAX_SEATS = (\d+)/)[1];
  assert.match(limits, new RegExp(`RIDE_MIN_SEATS = ${min};`));
  assert.match(limits, new RegExp(`RIDE_MAX_SEATS = ${max};`));
});

test('the committed mirror is exactly what the domain code generates (run the script to refresh it)', () => {
  for (const [name, text] of generateMirror()) {
    const committed = readFileSync(join(ROOT, MIRROR_DIR, name), 'utf8');
    assert.equal(committed, text, `${MIRROR_DIR}/${name} is out of date`);
  }
});

test('no test files of the domain are mirrored', () => {
  for (const name of generateMirror().keys()) assert.doesNotMatch(name, /test/i);
});
